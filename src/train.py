"""Training loop and CLI for the baseline TinyLM (control arm).

See implementation/06_agent_briefs/B3_baseline_model.md for the full
requirements table. Summary of what this module guarantees:

* ``--seed`` gives bit-identical runs (R3), including a pinned thread count
  (implementation/03_edge_cases_and_scares.md H3 -- float reduction order
  depends on thread count, so determinism is only a meaningful claim under a
  *fixed* thread count).
* Checkpoint + resume gives bit-identical final weights vs an uninterrupted
  run (R4): resuming restores optimiser state, RNG state, *and* dataloader
  position, not just model weights (H4).
* NaN/Inf loss aborts immediately with the step number (R6) via
  :class:`TrainingDivergedError`.
* No network is touched anywhere in this module (R7).

Data: this module does not depend on ``src/data`` (out of B3's scope --
see the brief). Training and all required tests run against a small,
deterministic, in-memory synthetic token stream generated by
:func:`make_toy_dataset`. This keeps P0 (harness correctness) fully
self-contained and fast (R8: seconds, not minutes, on a 4-core CPU
container) while a later integration step points this same loop at the real
corpus from ``src/data/generate.py`` by swapping only the tensor passed as
``data`` -- the training loop itself is agnostic to where the token ids come
from.
"""

