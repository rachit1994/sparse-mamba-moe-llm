def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Train the baseline TinyLM (control arm). See "
        "implementation/06_agent_briefs/B3_baseline_model.md."
    )
    parser.add_argument("--seed", type=int, required=True, help="determinism seed")
    parser.add_argument(
        "--config", type=str, default="tiny", choices=sorted(PRESET_CONFIGS), help="preset model config"
    )
    parser.add_argument("--steps", type=int, required=True, help="total optimizer steps to reach")
    parser.add_argument("--batch-size", type=int, default=4, help="batch size")
    parser.add_argument("--lr", type=float, default=3e-4, help="AdamW learning rate")
    parser.add_argument("--weight-decay", type=float, default=0.0, help="AdamW weight decay")
    parser.add_argument(
        "--n-examples",
        type=int,
        default=20,
        help="size of the in-memory synthetic toy dataset (see make_toy_dataset; "
        "this CLI does not yet read src/data's real corpus -- out of B3's scope)",
    )
    parser.add_argument("--out-dir", type=Path, required=True, help="checkpoint output directory")
    parser.add_argument("--resume", type=Path, default=None, help="checkpoint file to resume from")
    parser.add_argument("--num-threads", type=int, default=1, help="pinned torch thread count (H3)")
    parser.add_argument(
        "--checkpoint-every", type=int, default=0, help="write a periodic checkpoint every N steps (0 = final only)"
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    """CLI entry point. Returns a process exit code (0 success, 1 divergence)."""
    args = _build_arg_parser().parse_args(argv)
    config = PRESET_CONFIGS[args.config]
    data = make_toy_dataset(args.n_examples, config, args.seed)

    try:
        result = train_loop(
            config=config,
            seed=args.seed,
            steps=args.steps,
            batch_size=args.batch_size,
            lr=args.lr,
            data=data,
            out_dir=args.out_dir,
            resume_path=args.resume,
            num_threads=args.num_threads,
            checkpoint_every=args.checkpoint_every,
            weight_decay=args.weight_decay,
        )
    except TrainingDivergedError as exc:
        print(f"TRAINING DIVERGED: {exc}", file=sys.stderr)
        return 1

    final_loss = result.loss_history[-1] if result.loss_history else float("nan")
    print(f"final step {result.final_step}, final loss {final_loss:.6f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
