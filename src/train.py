def make_toy_dataset(n_examples: int, config: ModelConfig, seed: int) -> torch.Tensor:
    """Deterministic in-memory synthetic token sequences.

    Not the real training corpus -- see ``src/data/generate.py`` (owned by a
    different agent) for that. Exists so the required determinism/resume/
    overfit tests (and CLI smoke runs) are self-contained, need no files on
    disk, and run in seconds (R8).

    Uses a local ``torch.Generator`` seeded explicitly rather than the
    global torch RNG, so calling this function never perturbs (and is never
    perturbed by) the model-initialisation / training-step RNG stream --
    dataset construction and training are independently reproducible given
    the same ``seed``.

    Args:
        n_examples: number of example sequences. Must be a positive int.
        config: supplies ``vocab_size`` (token id range) and ``block_size``
            (sequence length -- every toy example is exactly this long).
        seed: determinism seed for this dataset only.

    Returns:
        Token ids, shape ``(n_examples, config.block_size)``, dtype
        ``torch.long``, values in ``[0, config.vocab_size)``.

    Raises:
        ValueError: if ``n_examples`` is not a positive int.
    """
    if isinstance(n_examples, bool) or not isinstance(n_examples, int) or n_examples <= 0:
        raise ValueError(f"n_examples must be a positive int, got {n_examples!r}")
    generator = torch.Generator().manual_seed(seed)
    return torch.randint(
        0, config.vocab_size, (n_examples, config.block_size), generator=generator, dtype=torch.long
    )


class ToyBatcher:
    """Deterministic, checkpointable batcher over a fixed set of token sequences.

    Not a general-purpose dataloader: its only job is to hand out shuffled
    batches and to be exactly resumable from a mid-epoch position
    (implementation/03_edge_cases_and_scares.md H4: "Optimiser state, RNG
    state, and dataloader position must all be restored. Restoring weights
    alone gives a run that looks fine and silently differs."). Every piece
    of mutable state (``_order``, ``_pos``, the shuffle generator) is
    captured by :meth:`state_dict` and restored by :meth:`load_state_dict`,
    so a resumed batcher draws the *identical* sequence of batches an
    uninterrupted one would have.

    When the remaining examples in the current epoch are fewer than
    ``batch_size``, the batcher reshuffles and starts a new epoch (the
    partial remainder is dropped, standard ``drop_last`` behaviour -- with
    ``n_examples`` as small as 20 in the tests, keeping a variable-size
    final batch would complicate the resume-equality check for no benefit).
    """

    def __init__(self, data: torch.Tensor, batch_size: int, seed: int) -> None:
        if data.dim() != 2:
            raise ValueError(f"data must be 2D (n_examples, seq_len), got shape {tuple(data.shape)}")
        if data.shape[0] == 0:
            raise ValueError("data must contain at least one example")
        if isinstance(batch_size, bool) or not isinstance(batch_size, int) or not (1 <= batch_size <= data.shape[0]):
            raise ValueError(f"batch_size must be an int in [1, {data.shape[0]}], got {batch_size!r}")
        self.data = data
        self.batch_size = batch_size
        self._generator = torch.Generator().manual_seed(seed)
        self._order = torch.randperm(data.shape[0], generator=self._generator)
        self._pos = 0

    def next_batch(self) -> torch.Tensor:
        """Return the next shuffled batch, reshuffling into a new epoch if needed.

        Returns:
            Token ids, shape ``(batch_size, seq_len)`` -- a view-independent
            copy is not guaranteed; treat as read-only.
        """
        if self._pos + self.batch_size > self.data.shape[0]:
            self._order = torch.randperm(self.data.shape[0], generator=self._generator)
            self._pos = 0
        indices = self._order[self._pos:self._pos + self.batch_size]
        self._pos += self.batch_size
        return self.data[indices]

    def state_dict(self) -> dict[str, Any]:
        """Everything needed to resume drawing the identical batch sequence."""
        return {
            "order": self._order.clone(),
            "pos": self._pos,
            "generator_state": self._generator.get_state().clone(),
        }

    def load_state_dict(self, state: dict[str, Any]) -> None:
        """Inverse of :meth:`state_dict`. Overwrites all current batcher state."""
        self._order = state["order"].clone()
        self._pos = state["pos"]
        self._generator.set_state(state["generator_state"].clone())


