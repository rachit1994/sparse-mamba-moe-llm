def _compute_lm_loss(model: TinyLM, batch: torch.Tensor) -> torch.Tensor:
    """Standard next-token cross-entropy loss (mean-reduced, in nats) over a batch.

    This is the *training* objective, and is deliberately independent of
    ``src.metrics.bits``'s bits/answer-token convention (that module's
    sum-reduction and bits conversion are for the evaluation metric, not
    the training loss -- implementation/02_testing_philosophy.md section 5
    is about the headline metric, not what the optimizer minimises). Every
    position is scored; there is no prompt/answer distinction at training
    time for this control-arm model.

    Args:
        model: a `TinyLM` instance.
        batch: token ids, shape ``(batch, seq_len)``, ``seq_len >= 2``.

    Returns:
        Scalar loss tensor (nats, mean-reduced over all predicted positions).
    """
    logits = model(batch[:, :-1])
    targets = batch[:, 1:]
    return F.cross_entropy(logits.reshape(-1, logits.size(-1)), targets.reshape(-1))


@dataclass
class TrainResult:
    """Everything a caller (or test) needs after :func:`train_loop` returns.

    Attributes:
        final_step: the last completed optimizer step.
        loss_history: one training loss value (float, nats) per completed
            step, in order, from step 1 (or the resumed start step + 1) up
            to ``final_step``. On a resumed run this includes the loss
            history restored from the checkpoint, so it is a full history
            from step 1 regardless of interruption.
        model: the trained model.
        optimizer: the optimizer, with its final state.
        batcher: the data batcher, with its final position.
    """

    final_step: int
    loss_history: list[float] = field(default_factory=list)
    model: TinyLM | None = None
    optimizer: torch.optim.Optimizer | None = None
    batcher: ToyBatcher | None = None


def save_checkpoint(
    path: Path,
    *,
    step: int,
    model: TinyLM,
    optimizer: torch.optim.Optimizer,
    batcher: ToyBatcher,
    seed: int,
    config: ModelConfig,
    loss_history: list[float],
) -> None:
    """Write a full training checkpoint: weights, optimiser, RNG, and data position.

    Requirement R4 (implementation/06_agent_briefs/B3_baseline_model.md):
    "resuming must restore optimiser state, RNG state, and dataloader
    position, not just weights." All four are written here.

    Writes to a temporary file in the same directory and renames it into
    place (``Path.replace``, atomic on the same filesystem) so a process
    killed mid-write (implementation/03_edge_cases_and_scares.md, Training /
    Failure: "OOM mid-run: checkpoint survives") never leaves a
    partially-written, corrupt checkpoint at ``path`` -- either the old
    checkpoint (if any) or a complete new one, never a half-written one.

    Args:
        path: destination file path. Parent directory must already exist.
        step: the last completed optimizer step.
        model: model to save.
        optimizer: optimizer to save.
        batcher: data batcher to save.
        seed: the run's determinism seed (recorded for provenance).
        config: the model config (recorded for provenance, and checked on
            resume -- see :func:`train_loop`).
        loss_history: the full loss history up to and including ``step``.
    """
    payload = {
        "step": step,
        "model_state": model.state_dict(),
        "optimizer_state": optimizer.state_dict(),
        "rng_state": _capture_rng_state(),
        "data_state": batcher.state_dict(),
        "seed": seed,
        "config": asdict(config),
        "loss_history": list(loss_history),
    }
    tmp_path = path.with_suffix(path.suffix + ".tmp")
    torch.save(payload, tmp_path)
    tmp_path.replace(path)


def load_checkpoint(path: Path) -> dict[str, Any]:
    """Load a checkpoint written by :func:`save_checkpoint`.

    Uses ``weights_only=False``: this project's checkpoints are always
    produced locally by :func:`save_checkpoint` (never fetched over the
    network -- R7) and contain non-tensor payload (RNG state tuples, the
    loss history, the config dict) that ``weights_only=True`` cannot
    deserialise. This is safe under the trust model for this repository's
    own artifacts and would not be an appropriate default for a checkpoint
    of unknown provenance.

    Args:
        path: checkpoint file path.

    Returns:
        The dict written by :func:`save_checkpoint`.

    Raises:
        FileNotFoundError: if ``path`` does not exist.
    """
    if not path.exists():
        raise FileNotFoundError(f"checkpoint not found: {path}")
    return torch.load(path, map_location="cpu", weights_only=False)


def _guard_fresh_out_dir(out_dir: Path) -> None:
    """Refuse to start a fresh run into a directory that already has checkpoints.

    implementation/03_edge_cases_and_scares.md, Training / Concurrent: "two
    runs, same output dir -> fail fast, do not interleave."
    """
    if out_dir.exists() and any(out_dir.glob("*.pt")):
        raise FileExistsError(
            f"{out_dir} already contains checkpoint(s) and resume_path was not given; "
            f"refusing to overwrite or interleave with a previous run. Pass --resume "
            f"to continue it, or use a fresh out_dir."
        )


def _validate_resume_config(checkpoint_config: dict[str, Any], config: ModelConfig) -> None:
    """Refuse to resume a checkpoint into a differently-shaped model.

    Without this check, a shape mismatch between the checkpoint's weights
    and the freshly-constructed model would surface as a confusing
    ``RuntimeError`` from deep inside ``load_state_dict`` (or, in
    pathological cases where total element counts happen to coincide, could
    silently load garbage). This check fails fast with the actual
    mismatched fields named.

    Raises:
        ValueError: if ``checkpoint_config != asdict(config)``.
    """
    current = asdict(config)
    if checkpoint_config != current:
        raise ValueError(
            f"cannot resume: checkpoint config {checkpoint_config} != requested config {current}"
        )


def train_loop(
    *,
    config: ModelConfig,
    seed: int,
    steps: int,
    batch_size: int,
    lr: float,
    data: torch.Tensor,
    out_dir: Path | None = None,
    resume_path: Path | None = None,
    num_threads: int = 1,
    checkpoint_every: int = 0,
    weight_decay: float = 0.0,
) -> TrainResult:
    """Train (or resume-and-continue-training) a `TinyLM` to `steps` total steps.

    Determinism (R3): calls :func:`set_determinism` itself, so it is
    reproducible whether invoked directly or via the CLI. Model
    construction, optimizer construction, and the data batcher's initial
    shuffle all happen *after* seeding, in a fixed order, so two calls with
    identical arguments (and no ``resume_path``) produce bit-identical
    final weights.

    Resume (R4): when ``resume_path`` is given, the model/optimizer/batcher
    are still constructed fresh (from ``config``/``seed``/``data``) and then
    every piece of mutable state is *overwritten* from the checkpoint --
    weights, optimizer state, RNG state, and batcher position (H4). This
    means "10 steps straight" and "5 steps, checkpoint, resume, 5 more
    steps" are required to produce bit-identical final weights, and the
    test suite asserts exactly that.

    NaN/Inf (R6): checked every step, immediately after the forward pass,
    before ``backward()``/``step()`` run. On divergence, raises
    :class:`TrainingDivergedError` naming the step and does not write a
    checkpoint for that step.

    Args:
        config: model architecture.
        seed: determinism seed.
        steps: total optimizer steps to reach (not steps *from here* --
            if resuming from step 5 with ``steps=10``, only 5 more steps
            run).
        batch_size: batch size, must be in ``[1, data.shape[0]]``.
        lr: AdamW learning rate.
        data: token ids, shape ``(n_examples, config.block_size)`` (e.g.
            from :func:`make_toy_dataset`).
        out_dir: if given, a final checkpoint (``out_dir/final.pt``) is
            always written, and -- unless ``resume_path`` is also given --
            the directory is checked for pre-existing checkpoints first
            (concurrent-run guard, see :func:`_guard_fresh_out_dir`).
        resume_path: if given, resume from this checkpoint file.
        num_threads: pinned torch thread count (H3); must match between any
            two runs being compared for bit-identity.
        checkpoint_every: if > 0, also write ``out_dir/step_{n}.pt`` every
            this many steps. 0 (default) disables periodic checkpoints; the
            final checkpoint (if ``out_dir`` is given) is always written
            regardless.
        weight_decay: AdamW weight decay. Defaults to ``0.0`` -- deliberately
            *not* torch's ``AdamW`` default of ``0.01``, which is a silent,
            unrequested regulariser that (empirically verified while
            building tests/test_models_tiny_lm.py's overfit test) puts a
            floor under the training loss well above 0 and would make
            "drive loss to ~0 on 20 examples" impossible to satisfy
            honestly.

    Returns:
        A :class:`TrainResult` with the final model, optimizer, batcher, and
        the full loss history.

    Raises:
        ValueError: if ``steps < 0``, or (via :func:`_validate_resume_config`)
            if resuming into a mismatched config.
        FileExistsError: if ``out_dir`` already holds checkpoint(s) and
            ``resume_path`` is ``None``.
        TrainingDivergedError: if the loss is non-finite at any step.
    """
    if isinstance(steps, bool) or not isinstance(steps, int) or steps < 0:
        raise ValueError(f"steps must be a non-negative int, got {steps!r}")

    set_determinism(seed, num_threads)

    model = TinyLM(config)
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=weight_decay)
    batcher = ToyBatcher(data, batch_size, seed=seed)

    start_step = 0
    loss_history: list[float] = []

    if resume_path is not None:
        checkpoint = load_checkpoint(resume_path)
        _validate_resume_config(checkpoint["config"], config)
        model.load_state_dict(checkpoint["model_state"])
        optimizer.load_state_dict(checkpoint["optimizer_state"])
        _restore_rng_state(checkpoint["rng_state"])
        batcher.load_state_dict(checkpoint["data_state"])
        start_step = checkpoint["step"]
        loss_history = list(checkpoint["loss_history"])
    elif out_dir is not None:
        _guard_fresh_out_dir(out_dir)

    if out_dir is not None:
        out_dir.mkdir(parents=True, exist_ok=True)

    for step in range(start_step + 1, steps + 1):
        batch = batcher.next_batch()
        optimizer.zero_grad(set_to_none=True)
        loss = _compute_lm_loss(model, batch)
        if not torch.isfinite(loss):
            kind = "NaN" if torch.isnan(loss) else "Inf"
            raise TrainingDivergedError(f"loss is {kind} at step {step}; aborting immediately")
        loss.backward()
        optimizer.step()
        loss_history.append(float(loss.detach()))

        if out_dir is not None and checkpoint_every and step % checkpoint_every == 0:
            save_checkpoint(
                out_dir / f"step_{step}.pt",
                step=step,
                model=model,
                optimizer=optimizer,
                batcher=batcher,
                seed=seed,
                config=config,
                loss_history=loss_history,
            )

    if out_dir is not None:
        save_checkpoint(
            out_dir / "final.pt",
            step=steps,
            model=model,
            optimizer=optimizer,
            batcher=batcher,
            seed=seed,
            config=config,
            loss_history=loss_history,
        )

    return TrainResult(
        final_step=steps, loss_history=loss_history, model=model, optimizer=optimizer, batcher=batcher
    )


