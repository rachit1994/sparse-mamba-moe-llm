class TrainingDivergedError(RuntimeError):
    """Raised when the training loss is non-finite (NaN or Inf).

    Requirement R6 (implementation/06_agent_briefs/B3_baseline_model.md):
    never train through a diverged run
    (implementation/03_edge_cases_and_scares.md, Training / Untrusted). The
    step number at which divergence was detected is always included in the
    message; the loop stops immediately -- no further optimizer steps run
    and no checkpoint is written for the diverged step.
    """


# ---------------------------------------------------------------------------
# Determinism (implementation/02_testing_philosophy.md section 4; H3)
# ---------------------------------------------------------------------------


def set_determinism(seed: int, num_threads: int = 1) -> None:
    """Seed every RNG this project touches and pin the thread count.

    Mirrors the reference implementation in
    implementation/02_testing_philosophy.md section 4 exactly, plus pinning
    ``torch``'s intra-op thread count (implementation/03_edge_cases_and_scares.md
    H3: different thread counts change floating-point reduction order, so
    two runs are only guaranteed bit-identical under the *same* thread
    count -- callers that hash-compare two runs must pass the same
    ``num_threads`` to both).

    Note on ``PYTHONHASHSEED``: setting the environment variable here does
    **not** change the hash seed of the *current*, already-running
    interpreter (CPython reads it once at start-up) -- only of processes
    spawned afterwards. It is set anyway to match the documented reference
    function and because it is harmless; it is not what makes this
    process's runs reproducible. Nothing in this module's own code
    (`TinyLM`, `ToyBatcher`, the training loop) iterates over a `set` or an
    unordered `dict` view in a way whose order could affect a numeric
    result, so residual hash-order risk here is believed to be zero, but it
    is not a stronger guarantee than that.

    Args:
        seed: the determinism seed.
        num_threads: torch intra-op thread count to pin. Defaults to 1 (the
            strongest determinism guarantee available); real training runs
            on the Mac mini target may pass a larger value for throughput,
            but any two runs being hash-compared for bit-identity must use
            the same value.

    Raises:
        ValueError: if ``num_threads`` is not a positive int.
    """
    if isinstance(num_threads, bool) or not isinstance(num_threads, int) or num_threads <= 0:
        raise ValueError(f"num_threads must be a positive int, got {num_threads!r}")
    os.environ["PYTHONHASHSEED"] = str(seed)
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.use_deterministic_algorithms(True, warn_only=True)
    torch.set_num_threads(num_threads)


def _capture_rng_state() -> dict[str, Any]:
    """Snapshot every RNG stream that could affect a subsequent training step."""
    return {
        "python": random.getstate(),
        "numpy": np.random.get_state(),
        "torch": torch.get_rng_state(),
        "torch_cuda": torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
    }


def _restore_rng_state(state: dict[str, Any]) -> None:
    """Inverse of :func:`_capture_rng_state`."""
    random.setstate(state["python"])
    np.random.set_state(state["numpy"])
    torch.set_rng_state(state["torch"])
    if state["torch_cuda"] is not None and torch.cuda.is_available():
        torch.cuda.set_rng_state_all(state["torch_cuda"])


